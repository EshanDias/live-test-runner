#!/usr/bin/env node
'use strict';
/**
 * Embeds src/framework/pytest/ltr_pytest.py (the source of truth, tested
 * with pytest) into src/framework/pytest/ltrPytestSource.ts, which the
 * runner writes to the session folder at runtime — like the Vitest reporter.
 *
 *   node scripts/embed-pytest-plugin.js           write the .ts
 *   node scripts/embed-pytest-plugin.js --check   fail when it is out of date
 */
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'src', 'framework', 'pytest');
const py = fs.readFileSync(path.join(dir, 'ltr_pytest.py'), 'utf8').replace(/\r\n/g, '\n');
const out = path.join(dir, 'ltrPytestSource.ts');
const ts =
  '// Generated by scripts/embed-pytest-plugin.js from ltr_pytest.py — do not edit.\n' +
  `export const LTR_PYTEST_SOURCE: string = ${JSON.stringify(py)};\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== ts) {
    console.error('ltrPytestSource.ts is out of date — run: node packages/runner/scripts/embed-pytest-plugin.js');
    process.exit(1);
  }
} else if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== ts) {
  fs.writeFileSync(out, ts, 'utf8');
}
